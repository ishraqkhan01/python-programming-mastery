print("Python String Formatter")
user_text = input("Enter any sentence or text: ")

uppercase_text = user_text.upper()
print(f"upper(): {uppercase_text}")

lowercase_text = user_text.lower()
print(f"lower(): {lowercase_text}")

title_text = user_text.title()
print(f"title(): {title_text}")

capitalize_text = user_text.capitalize()
print(f"capitalize(): {capitalize_text}")